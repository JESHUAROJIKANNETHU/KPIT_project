// ============================================================
// Vehicle Assembly Data Model
// Hierarchical component tree with engineering parameters
// DATA TYPE: Prototype / Demonstration
// ============================================================

export interface ComponentParameter {
  name: string;
  value: number | string;
  unit: string;
  editable: boolean;
  min?: number;
  max?: number;
  step?: number;
  category: 'general' | 'geometry' | 'performance' | 'thermal' | 'cost' | 'durability';
  dataType: 'DEMO' | 'REFERENCE' | 'SIMULATION' | 'ML_PREDICTION';
}

export interface AssemblyNode {
  id: string;
  name: string;
  type: 'assembly' | 'part';
  partId?: string;
  material?: string;
  mass?: number; // kg
  visible: boolean;
  selected: boolean;
  expanded: boolean;
  color: string;
  position: [number, number, number];
  dimensions?: [number, number, number]; // width, height, depth in mm
  explosionVector?: [number, number, number]; // directional explosion vector
  parameters: ComponentParameter[];
  children: AssemblyNode[];
}

