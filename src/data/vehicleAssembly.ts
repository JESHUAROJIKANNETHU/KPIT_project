// Flatten assembly tree to list for lookups
export const flattenAssembly = (node: AssemblyNode): AssemblyNode[] => {
  const result: AssemblyNode[] = [node];
  for (const child of node.children) {
    result.push(...flattenAssembly(child));
  }
  return result;
};

// Get path from root to a given node
export const getAssemblyPath = (root: AssemblyNode, targetId: string): string[] => {
  const path: string[] = [];
  const find = (node: AssemblyNode, currentPath: string[]): boolean => {
    currentPath.push(node.name);
    if (node.id === targetId) {
      path.push(...currentPath);
      return true;
    }
    for (const child of node.children) {
      if (find(child, [...currentPath])) return true;
    }
    return false;
  };
  find(root, []);
  return path;
};
